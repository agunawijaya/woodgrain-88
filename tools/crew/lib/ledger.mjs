/**
 * The ledger: one entry per work order, so the owner can see what the crew did
 * and whether delegating saved Claude tokens. `.team/ledger.json` is the data;
 * `.team/LEDGER.md` is rendered from it after every change and both are tracked.
 *
 * Lead token figures are the lead's own estimates (set with `crew review`):
 * what writing and reviewing the order cost, and what doing the work alone
 * would have cost. Savings are the difference, summed.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';

export const LEDGER_JSON = '.team/ledger.json';
export const LEDGER_MD = '.team/LEDGER.md';

export function readLedger(repoRoot) {
  const file = join(repoRoot, LEDGER_JSON);
  if (!existsSync(file)) return { orders: [] };
  return JSON.parse(readFileSync(file, 'utf8'));
}

function emptyTokens() {
  return { input: 0, output: 0, thinking: 0, cacheRead: 0, total: 0 };
}

function addTokens(a, b) {
  return {
    input: a.input + b.input,
    output: a.output + b.output,
    thinking: a.thinking + b.thinking,
    cacheRead: a.cacheRead + b.cacheRead,
    total: a.total + b.total,
  };
}

/** Folds one finished round into the order's ledger entry. */
export function recordRound(
  ledger,
  { id, kind, model, member = 'agy', status, seconds, tokens, violations, at },
) {
  let entry = ledger.orders.find((order) => order.id === id);
  if (!entry) {
    entry = {
      id,
      kind,
      model,
      member,
      rounds: 0,
      status,
      seconds: 0,
      crewTokens: emptyTokens(),
      violations: 0,
      leadTokens: null,
      soloTokens: null,
      note: '',
      startedAt: at,
    };
    ledger.orders.push(entry);
  }
  entry.model = model;
  entry.member = member;
  entry.rounds += 1;
  entry.status = status;
  entry.seconds = Math.round((entry.seconds + seconds) * 10) / 10;
  entry.crewTokens = addTokens(entry.crewTokens, tokens);
  entry.violations += violations;
  entry.updatedAt = at;
  return entry;
}

export const VERDICTS = ['accepted', 'rejected', 'taken-over'];

export function recordReview(ledger, { id, verdict, leadTokens, soloTokens, note, at }) {
  const entry = ledger.orders.find((order) => order.id === id);
  if (!entry) throw new Error(`No ledger entry for order ${id}.`);
  if (verdict !== undefined) {
    if (!VERDICTS.includes(verdict))
      throw new Error(`Verdict must be one of ${VERDICTS.join(', ')}.`);
    entry.status = verdict;
  }
  if (leadTokens !== undefined) entry.leadTokens = leadTokens;
  if (soloTokens !== undefined) entry.soloTokens = soloTokens;
  if (note !== undefined) entry.note = note;
  entry.updatedAt = at;
  return entry;
}

export function ledgerTotals(ledger) {
  const totals = {
    orders: ledger.orders.length,
    rounds: 0,
    seconds: 0,
    crewTokens: emptyTokens(),
    leadTokens: 0,
    soloTokens: 0,
    estimatedSaving: 0,
    reviewed: 0,
    byStatus: {},
  };
  for (const order of ledger.orders) {
    totals.rounds += order.rounds;
    totals.seconds += order.seconds;
    totals.crewTokens = addTokens(totals.crewTokens, order.crewTokens);
    totals.byStatus[order.status] = (totals.byStatus[order.status] ?? 0) + 1;
    if (order.leadTokens !== null && order.soloTokens !== null) {
      totals.reviewed += 1;
      totals.leadTokens += order.leadTokens;
      totals.soloTokens += order.soloTokens;
      totals.estimatedSaving += order.soloTokens - order.leadTokens;
    }
  }
  totals.seconds = Math.round(totals.seconds);
  return totals;
}

const formatCount = (value) => (value === null ? '–' : value.toLocaleString('en-GB'));

function formatMinutes(seconds) {
  return `${Math.round(seconds / 6) / 10} min`;
}

const plural = (count, word) => `${count} ${word}${count === 1 ? '' : 's'}`;

function describeSaving(saving) {
  if (saving >= 0) return `**about ${formatCount(saving)} Claude tokens saved**`;
  return `**about ${formatCount(-saving)} more Claude tokens than working solo**`;
}

function escapeCell(text) {
  return String(text).replaceAll('|', '\\|').replaceAll('\n', ' ');
}

export function renderLedger(ledger) {
  const totals = ledgerTotals(ledger);
  const statusSummary =
    Object.entries(totals.byStatus)
      .map(([status, count]) => `${count} ${status}`)
      .join(', ') || 'none yet';
  const lines = [
    '# Crew ledger',
    '',
    '> Generated by `pnpm crew` from `.team/ledger.json`; do not edit by hand.',
    '',
    `**Totals:** ${plural(totals.orders, 'order')} (${statusSummary}) · ${plural(totals.rounds, 'round')} · ` +
      `${formatMinutes(totals.seconds)} of crew time · ` +
      `${formatCount(totals.crewTokens.total)} crew tokens · ` +
      `lead estimate on ${plural(totals.reviewed, 'reviewed order')}: ${formatCount(totals.leadTokens)} Claude tokens spent ` +
      `vs ${formatCount(totals.soloTokens)} solo, ${describeSaving(totals.estimatedSaving)}.`,
    '',
    '| Order | Kind | Model | Member | Rounds | Status | Duration | Crew tokens | Fence violations | Lead tokens (spent / solo est.) | Note |',
    '|---|---|---|---|---|---|---|---|---|---|---|',
  ];
  for (const order of ledger.orders) {
    lines.push(
      `| ${order.id} | ${order.kind} | ${order.model} | ${order.member ?? 'agy'} | ${order.rounds} | ${order.status} | ` +
        `${formatMinutes(order.seconds)} | ${formatCount(order.crewTokens.total)} | ${order.violations} | ` +
        `${formatCount(order.leadTokens)} / ${formatCount(order.soloTokens)} | ${escapeCell(order.note)} |`,
    );
  }
  return `${lines.join('\n')}\n`;
}

export function writeLedger(repoRoot, ledger) {
  const jsonFile = join(repoRoot, LEDGER_JSON);
  mkdirSync(dirname(jsonFile), { recursive: true });
  writeFileSync(jsonFile, `${JSON.stringify(ledger, null, 2)}\n`);
  writeFileSync(join(repoRoot, LEDGER_MD), renderLedger(ledger));
}
