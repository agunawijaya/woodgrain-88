// Writes sw.js into the build: a small service worker that keeps every built
// file after the first visit, so the Den and every game work offline. The
// site makes no cross-origin requests, so a plain precache is enough.
import type { Plugin } from 'vite';

const CACHE_PREFIX = 'woodgrain-88-';

// Built file names carry content hashes, so a hash of the list changes
// exactly when anything shipped changed.
function fingerprint(files: readonly string[]): string {
  let hash = 0x811c9dc5;
  for (const char of files.join('\n')) {
    hash ^= char.charCodeAt(0);
    hash = Math.imul(hash, 0x01000193);
  }
  return (hash >>> 0).toString(36);
}

function serviceWorkerSource(files: readonly string[], version: string): string {
  const precache = JSON.stringify(['./', ...files.map((file) => `./${file}`)]);
  return `// Generated by hall/build/offline-precache.ts. Do not edit by hand.
const CACHE = '${CACHE_PREFIX}${version}';
const PRECACHE = ${precache};

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(PRECACHE)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((key) => key.startsWith('${CACHE_PREFIX}') && key !== CACHE).map((key) => caches.delete(key))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET' || new URL(request.url).origin !== self.location.origin) return;
  // The page itself: the network first so a new deploy shows up, the cache when offline.
  if (request.mode === 'navigate') {
    event.respondWith(fetch(request).catch(() => caches.match('./', { ignoreSearch: true })));
    return;
  }
  // Hashed assets never change once built, so a cached copy is always right.
  event.respondWith(caches.match(request, { ignoreVary: true }).then((cached) => cached || fetch(request)));
});
`;
}

export function offlinePrecache(): Plugin {
  return {
    name: 'woodgrain-88:offline-precache',
    apply: 'build',
    enforce: 'post',
    generateBundle(_options, bundle) {
      const files = Object.keys(bundle)
        .filter((file) => !file.endsWith('.map'))
        .sort();
      this.emitFile({
        type: 'asset',
        fileName: 'sw.js',
        source: serviceWorkerSource(files, fingerprint(files)),
      });
    },
  };
}
